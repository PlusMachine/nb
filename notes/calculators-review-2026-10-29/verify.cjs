const { chromium }=require('playwright');
const fs=require('node:fs/promises');
const path=require('node:path');
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:1100,height:1100},locale:'ru-RU'});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('file://'+path.join(__dirname,'preview.html'));
 const frame=page.frameLocator('iframe');
 await frame.locator('#nb-review-picker').waitFor();
 const options=await frame.locator('#nb-review-picker option').evaluateAll(es=>es.map(e=>({id:e.value,name:e.textContent})));
 console.log('OPTIONS',options.length);
 const results=[];await fs.mkdir(path.join(__dirname,'after'),{recursive:true});
 for(const width of [1100,390]){
  await page.setViewportSize({width,height:1100});
  for(const c of options){
   await frame.locator('#nb-review-picker').selectOption(c.id);
   const title=await frame.locator('#nb-review-after h2').textContent();
   if(title!==c.name)throw Error('Wrong title '+c.id);
   const layout=await frame.locator('#nb-review-after').evaluate(e=>({width:e.clientWidth,scroll:e.scrollWidth}));
   if(layout.scroll>layout.width+2)throw Error('Overflow '+c.id+' '+width+' '+JSON.stringify(layout));
   if(['water-ph','ibu','bottling','brewing-water-volume','index','abv-attenuation'].includes(c.id))await frame.locator('#nb-review-after').screenshot({path:path.join(__dirname,'after',c.id+'-'+width+'.png')});
   results.push({id:c.id,width,passed:true});
  }
 }
 await frame.locator('#nb-review-picker').selectOption('abv-attenuation');
 await frame.locator('[data-input=og]').fill('13,0');
 const comma=await frame.locator('#nb-live-result').innerText();
 await frame.locator('[data-input=og]').fill('13.0');
 const dot=await frame.locator('#nb-live-result').innerText();
 if(comma!==dot)throw Error('Decimal separator mismatch');
 await frame.locator('[data-input=fg]').fill('-1');
 if((await frame.locator('#nb-live-result').innerText()).includes('Проверьте данные'))throw Error('Negative FG must remain supported');
 await frame.locator('[data-input=og]').fill('');
 if(!(await frame.locator('#nb-live-result').innerText()).includes('Проверьте данные'))throw Error('Missing empty state');
 await frame.locator('#nb-review-picker').selectOption('bottling');
 await frame.getByRole('button',{name:'0,33 л',exact:true}).click();
 const bottles=await frame.locator('#nb-live-result').innerText();
 if(!bottles.includes('60')||!bottles.includes('59')||!bottles.includes('30 мл'))throw Error('Bottling breakdown');
 await frame.locator('#nb-review-picker').selectOption('yeast-starter');
 await frame.getByRole('button',{name:'Пример без живых дрожжей'}).click();
 if(!(await frame.locator('#nb-result-body').innerText()).includes('Нужны свежие дрожжи'))throw Error('Yeast empty state');
 if(await frame.locator('[data-input=viability]').inputValue()!=='0')throw Error('Zero yeast source mismatch');
 await frame.locator('#nb-review-picker').selectOption('hop-freshness');
 await frame.getByRole('button',{name:'Считать хмель свежим'}).click();
 if(!(await frame.locator('#nb-result-body').innerText()).includes('Вы выбрали'))throw Error('Hop assumption');
 await frame.locator('#nb-review-picker').selectOption('priming-sugar');
 await frame.getByRole('button',{name:'На бутылку',exact:true}).click();
 if(!(await frame.locator('.hero').innerText()).includes('3,1'))throw Error('Sugar mode');
 await frame.locator('#nb-review-picker').selectOption('beer-color');
 await frame.getByRole('button',{name:'Пример без объёма партии'}).click();
 if(!(await frame.locator('#nb-result-body').innerText()).includes('Укажите объём'))throw Error('Color invalid state');
 await frame.locator('#nb-review-picker').selectOption('index');
 if(await frame.locator('.catalog-item').count()!==17)throw Error('All catalog must include 17 calculators');
 await frame.locator('#nb-review-picker').selectOption('water-ph');
 if(!(await frame.locator('#nb-result-body').innerText()).includes('Кислота в затор · 15 л'))throw Error('Acid volume label');
 await page.setViewportSize({width:1100,height:1100});
 await page.emulateMedia({colorScheme:'dark'});
 await frame.locator('#nb-review-after').screenshot({path:path.join(__dirname,'after','water-ph-dark.png')});
 await page.emulateMedia({colorScheme:'light'});
 console.log('BUTTONS',await frame.getByRole('button').allTextContents());
 const next=frame.getByRole('button',{name:'Следующий вариант',exact:true});
 await next.click();
 await frame.locator('#nb-review-before').waitFor({state:'visible'});
 const loaded=await frame.locator('#nb-review-before').evaluate(e=>e.complete&&e.naturalWidth>0);
 if(!loaded)throw Error('Before image failed');
 await page.setViewportSize({width:1100,height:1100});
 await page.screenshot({path:path.join(__dirname,'after','before-preview.png'),fullPage:true});
 if(errors.length)throw Error(errors.join('\n'));
 await fs.writeFile(path.join(__dirname,'verification.json'),JSON.stringify({screens:results,checks:['decimal comma','negative FG','empty required input','partial bottle','zero live yeast and source','explicit fresh hops assumption','priming mode','zero volume beer color','all 17 catalog cards','acid volume label','before/after carousel','before image loaded','dark theme screenshot'],pageErrors:errors},null,2));
 console.log('PASS',results.length,'responsive views and 13 checks');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
