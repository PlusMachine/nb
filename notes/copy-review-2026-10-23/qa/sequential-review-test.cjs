const { chromium }=require('playwright');
const path=require('path');
const fs=require('fs');
(async()=>{
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:736,height:900}});
 const errors=[];page.on('pageerror',e=>errors.push(String(e)));
 await page.goto('file://'+path.resolve('notes/copy-review-2026-10-23/qa/checklist-sequential-preview.html'));
 const frame=page.frames().find(f=>f!==page.mainFrame());
 const text=async id=>frame.locator('#'+id).innerText();
 const check=(value,message)=>{if(!value)throw Error(message);};
 await frame.locator('#nb-context').waitFor();
 check((await text('nb-position')).includes('R001'),'First item not shown');
 await frame.locator('#nb-approve').click();
 check((await text('nb-position')).includes('R002'),'Approve did not advance');
 await frame.locator('#nb-reject').click();
 check((await text('nb-position')).includes('R003'),'Reject did not advance');
 await frame.locator('#nb-custom').click();
 await frame.locator('#nb-save-custom').click();
 check((await text('nb-status')).includes('Напишите'),'Empty custom not blocked');
 await frame.locator('#nb-custom-text').fill('Мой собственный вариант <текст>');
 await frame.locator('#nb-save-custom').click();
 check((await text('nb-position')).includes('R004'),'Custom did not advance');
 await frame.locator('#nb-prev').click();
 check(await frame.locator('#nb-custom-text').inputValue()==='Мой собственный вариант <текст>','Custom not preserved');
 await frame.evaluate(()=>{window.openai.sendFollowUpMessage=async p=>{window.testPrompt=p.prompt;};});
 await frame.locator('#nb-send').click();
 const prompt=await frame.evaluate(()=>window.testPrompt);
 check(prompt.includes('Мой собственный вариант <текст>')&&prompt.includes('approve')&&prompt.includes('reject'),'Incomplete transfer');
 await frame.locator('#nb-jump').fill('320');await frame.locator('#nb-jump').press('Tab');
 check((await text('nb-position')).includes('R320'),'Last item not reachable');
 check(await frame.locator('#nb-next').isDisabled(),'Last item can go beyond bounds');
 await frame.locator('#nb-jump').fill('1');await frame.locator('#nb-jump').press('Tab');
 check(await frame.locator('#nb-approve').getAttribute('aria-pressed')==='true','Decision not restored');
 await frame.locator('#nb-reject').click();
 check((await text('nb-progress')).includes('3 из 320'),'Changed decision double counted');
 await page.screenshot({path:'notes/copy-review-2026-10-23/qa/sequential-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 const fit=await frame.evaluate(()=>({width:document.documentElement.clientWidth,scroll:document.documentElement.scrollWidth}));
 check(fit.scroll<=fit.width+1,'Mobile overflow');
 await page.screenshot({path:'notes/copy-review-2026-10-23/qa/sequential-mobile.png',fullPage:true});
 await frame.evaluate(()=>{window.openai.sendFollowUpMessage=undefined;});
 await frame.locator('#nb-send').click();
 check((await frame.locator('#nb-transfer').inputValue()).includes('Мой собственный вариант'),'Copy fallback lost decisions');
 check(!errors.length,errors.join('\n'));
 fs.writeFileSync('notes/copy-review-2026-10-23/qa/sequential-test-result.json',JSON.stringify({passed:true,items:320,fit,errors},null,2));
 console.log('PASS: sequential review, all choices, transfer, last item, mobile fit');await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
