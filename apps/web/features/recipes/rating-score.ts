/**
 * Байесовское среднее рейтинга (формула IMDb Top 250) — чистая функция без БД,
 * тестируется изолированно.
 *
 * Проблема наивного `rating_avg DESC`: рецепт с одной оценкой 5.0 стоит выше
 * рецепта с 4.8 при 120 оценках. Байесовский скор «подтягивает» малочисленные
 * оценки к априорному среднему `m`, и только с ростом числа оценок скор
 * приближается к реальному среднему:
 *
 *   bayes = (C·m + avg·n) / (C + n)
 *
 * где n — число оценок, avg — честное среднее, m — априорное среднее по платформе,
 * C — вес прайора в «псевдо-оценках».
 *
 * ВАЖНО: скор используется ТОЛЬКО для ORDER BY. Наружу (карточки, страница
 * рецепта) продолжаем показывать честный `avg` + число оценок.
 */

/** Априорное среднее (глобальное среднее по платформе). На MVP — константа. */
export const RATING_PRIOR_MEAN = 3.8;

/** Вес прайора в псевдо-оценках: сколько «виртуальных» оценок `m` подмешиваем. */
export const RATING_PRIOR_WEIGHT = 10;

/**
 * Байесовский скор рейтинга. `null`, если оценок нет (`count <= 0` или `avg == null`),
 * — такие рецепты сортировка «По рейтингу» отправляет в конец (NULLS LAST).
 */
export const computeBayesianRating = (avg: number | null, count: number): number | null => {
  if (avg == null || count <= 0) {
    return null;
  }
  return (RATING_PRIOR_WEIGHT * RATING_PRIOR_MEAN + avg * count) / (RATING_PRIOR_WEIGHT + count);
};
