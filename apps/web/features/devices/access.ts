import type { UserRole } from "@nb/auth";

// =============================================================================
//  Гейты доступности устройств. Раздел «Устройства» — фича в разработке:
//  связки с реальным железом (BrewForge, ареометры, RAPT) в поле не проверены.
//  Модуль без импортов БД — можно дёргать и из роутов, и из layout/страниц.
// =============================================================================

/** Демо-устройства (демо-пивоварня, демо-ареометр) — только для внутренних
 *  тестов и разработки. В production не доступны никому и никогда. */
export const canUseDemoDevices = (): boolean => process.env.NODE_ENV !== "production";

/** Реальные устройства: вне production — всем (dev/QA), в production — только
 *  админу (владелец сам проверяет связки с железом до открытия раздела). */
export const canUseDevices = (role: UserRole): boolean =>
  process.env.NODE_ENV !== "production" || role === "admin";
