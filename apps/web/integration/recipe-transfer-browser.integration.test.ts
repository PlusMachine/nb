import { randomUUID } from "node:crypto";
import { readFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { afterAll, afterEach, beforeAll, beforeEach, describe, it, expect as check } from "vitest";
import { chromium, expect, type Browser, type BrowserContext, type Page } from "@playwright/test";
import { db, pool, users, recipes, eq, inArray } from "@nb/db";
import { completeEmailSignIn, createSession } from "@nb/auth";
import { getRecipeById } from "../features/recipes/service";
import { importBeerXmlToCanonicalRecipe } from "../features/recipes/interop/beerxml";
const base = process.env.E2E_BASE_URL ?? "http://127.0.0.1:3000";
const artifactDir = fileURLToPath(new URL("../../../notes/qa-interop-2026-11-03/screenshots/", import.meta.url));
let browser: Browser, context: BrowserContext, page: Page, owner: string;
const owners: string[] = [];
const title = () => page.getByPlaceholder("Например, NEIPA с тропическим ароматом");
const hydrated = () => page.waitForFunction(() => Array.from(document.querySelectorAll("button")).some(button => button.textContent?.trim() === "Сварить" && Object.keys(button).some(key => key.startsWith("__reactProps$"))));
beforeAll(async () => {
  if (new URL(process.env.DATABASE_URL!).pathname !== "/nb_qa_20261103") throw new Error("ISOLATED_QA_DATABASE_REQUIRED");
  mkdirSync(artifactDir, { recursive: true }); browser = await chromium.launch({ headless: true });
});
beforeEach(async () => {
  owner = (await completeEmailSignIn({ email: `qa.transfer.${randomUUID()}@localhost` })).id; owners.push(owner);
  const session = await createSession({ userId: owner, userAgent: "QA transfer browser" });
  context = await browser.newContext({ viewport: { width: 1280, height: 900 }, locale: "ru-RU", timezoneId: "Europe/Moscow", acceptDownloads: true });
  await context.addCookies([{ name: "nb_session", value: session.rawToken, url: base }, { name: "nb_cookie_consent", value: "1:necessary", url: base }, { name: "nb_age_ok", value: "1", url: base }]);
  page = await context.newPage(); page.on("dialog", dialog => { void dialog.accept(); });
});
afterEach(async () => { await context?.close(); });
afterAll(async () => { await browser?.close(); if (owners.length) await db.delete(users).where(inArray(users.id, owners)); await pool.end(); });
describe("browser import, editing and BeerXML download", () => {
  for (const format of ["beerxml", "brewfather.json"]) it(`imports ${format}, edits, downloads BeerXML and reloads`, async () => {
    await page.goto(base + "/app/recipes/new", { waitUntil: "domcontentloaded" }); await hydrated();
    await page.getByRole("button", { name: "Импорт / экспорт", exact: true }).click();
    const dialog = page.getByRole("dialog", { name: "Импорт / экспорт", exact: true });
    await dialog.getByRole("button", { name: "Импортировать рецепт", exact: true }).click();
    if (format === "brewfather.json") await dialog.getByRole("button", { name: "Импорт из Brewfather", exact: true }).click();
    const input = readFileSync(new URL(`../../../ingredients/examples_for_import/apa_sunset_trail.checked.${format}`, import.meta.url));
    await dialog.locator('input[type="file"]').setInputFiles({ name: `qa.${format}`, mimeType: format === "beerxml" ? "text/xml" : "application/json", buffer: input });
    await expect(dialog.getByRole("button", { name: "Импортировать", exact: true })).toBeEnabled({ timeout: 15000 });
    await dialog.getByRole("button", { name: "Импортировать", exact: true }).click();
    await expect(page.getByRole("dialog", { name: "Сопоставить с каталогом", exact: true })).toBeVisible({ timeout: 15000 });
    await page.getByRole("dialog", { name: "Сопоставить с каталогом", exact: true }).getByRole("button", { name: "Отмена", exact: true }).click();
    await expect(title()).toHaveValue("Sunset Trail APA");
    const rows = await db.query.recipes.findMany({ where: eq(recipes.authorId, owner) }); check(rows).toHaveLength(1);
    const id = rows[0].id;
    await expect(page).toHaveURL(base + `/app/recipes/${id}/edit`);
    await title().fill("QA imported and edited " + format);
    await expect(page.getByText("Сохранено", { exact: true })).toBeVisible({ timeout: 15000 });
    check((await getRecipeById(owner, id)).title).toBe("QA imported and edited " + format);
    await page.getByRole("button", { name: "Импорт / экспорт", exact: true }).click();
    await dialog.getByRole("button", { name: "Экспортировать BeerXML", exact: true }).click();
    await expect(dialog.locator("textarea")).toContainText("QA imported and edited " + format, { timeout: 15000 });
    const downloadPromise = page.waitForEvent("download"); await dialog.getByRole("link", { name: "Скачать BeerXML", exact: true }).click();
    const download = await downloadPromise; check(download.suggestedFilename()).toBe("recipe.beerxml");
    const path = await download.path(); check(path).toBeTruthy();
    const exported = importBeerXmlToCanonicalRecipe(readFileSync(path!, "utf8"));
    check(exported.title).toBe("QA imported and edited " + format); check(exported.ingredients.length).toBeGreaterThan(0);
    await page.screenshot({ path: artifactDir + `transfer-${format}.png`, scale: "css", animations: "disabled" });
    await page.reload({ waitUntil: "domcontentloaded" }); await hydrated();
    await expect(title()).toHaveValue(exported.title);
    check(await db.query.recipes.findMany({ where: eq(recipes.authorId, owner) })).toHaveLength(1);
  });
});
